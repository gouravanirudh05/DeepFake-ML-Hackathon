"""Generate a Kaggle training notebook (+ kernel-metadata.json) from the repo sources.

The notebook embeds the source files via %%writefile, so Kaggle only needs this notebook plus the
private data dataset. Re-run this script after editing any source file, then push the kernel dir:

    python kaggle/make_notebook.py --preset sota-clip
    KAGGLE_API_TOKEN=... kaggle kernels push -p kaggle/kernels/deepfake-sota-clip --accelerator NvidiaTeslaT4
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ["src/__init__.py", "src/lora.py", "src/svd_adapter.py", "src/degradations.py", "src/sbi.py",
           "src/model.py", "src/data.py", "train.py", "build_bundle.py", "inference_script.py",
           "requirements.txt"]

CLIP = "vit_large_patch14_clip_224.openai"
BASE = "--feat_layers auto --drop_rate 0.08"           # = ml5_drop, best fold-0 config so far
EFFORT = "--adapter svd --svd_rank 4 --targets attn --lr 2e-4"
# preset -> (kernel slug, folds, {run name: train.py args})
PRESETS = {
    "ablation-v3": ("deepfake-clip-lora-train", [0], {
        "ml5": f"--arch {CLIP} --feat_layers auto",
        "ml5_drop": f"--arch {CLIP} {BASE}",
        "ml5_gce": f"--arch {CLIP} --feat_layers auto --loss gce",
    }),
    # SOTA generalisation components on CLIP: Effort (ICML'25) SVD subspace tuning, SBI pseudo-fakes
    "sota-clip": ("deepfake-sota-clip", [0], {
        "clip_effort": f"--arch {CLIP} {BASE} {EFFORT}",
        "clip_sbi": f"--arch {CLIP} {BASE} --sbi_prob 0.25",
        "clip_effort_sbi": f"--arch {CLIP} {BASE} {EFFORT} --sbi_prob 0.25",
    }),
    # diverse self-supervised / newer foundation backbones for the ensemble
    "sota-backbones": ("deepfake-sota-backbones", [0], {
        "dinov3_lora": f"--arch vit_large_patch16_dinov3.lvd1689m --img_size 224 {BASE}",
        "dinov2_lora": f"--arch vit_large_patch14_reg4_dinov2.lvd142m --img_size 224 {BASE}",
        "pe_lora": f"--arch vit_pe_core_large_patch14_336.fb --img_size 224 {BASE}",
    }),
}

cli = argparse.ArgumentParser()
cli.add_argument("--preset", choices=PRESETS, default="sota-clip")
cli.add_argument("--folds", default=None, help="override folds, e.g. 0,1,2,3,4")
cli.add_argument("--owner", default="gouravanirudh1105", help="Kaggle account that runs the kernel")
cli_args = cli.parse_args()
SLUG, FOLDS, RUNS = PRESETS[cli_args.preset]
if cli_args.folds:
    FOLDS = [int(f) for f in cli_args.folds.split(",")]
OUT_DIR = ROOT / "kaggle" / "kernels" / SLUG
OUT = OUT_DIR / f"{SLUG}.ipynb"


def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip("\n")}


def code(text):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.strip("\n")}


cells = [
    md("""
# Deepfake detection: foundation ViT + parameter-efficient tuning

Frozen foundation backbones (CLIP / DINOv3 / DINOv2 / PE) with LoRA or Effort-style SVD adapters, trained only on the hackathon data with grouped folds
(near-duplicate / real-fake pairs kept within one fold) and robustness augmentations.
Source files are embedded below via `%%writefile` (generated by `kaggle/make_notebook.py`).
"""),
    md("## Config: edit and run"),
    code(f"""
FOLDS  = {FOLDS!r}                     # e.g. [0,1,2,3,4] for full CV
COMMON = "--epochs 5 --bs 32 --grad_ckpt"
# experiment name -> train.py args (all compared on the same folds).
# Reference, fold 0: ml5_drop (CLIP-L LoRA, multi-layer CLS, small-loss 8%) clean AUC 0.9166.
RUNS = {json.dumps(RUNS, indent=4)}
RUN_TEST_INFERENCE = True   # bundle the best run's folds + time inference on the test set
"""),
    code("!pip install -q timm==1.0.31\n!nvidia-smi --query-gpu=name,memory.total --format=csv"),
    md("## Source files"),
]
for rel in SOURCES:
    text = (ROOT / rel).read_text()
    cells.append(code(f"%%writefile code/{rel}\n{text}"))
cells.insert(len(cells) - len(SOURCES), code("import os\nos.makedirs('code/src', exist_ok=True)"))

cells += [
    md("## Locate the dataset"),
    code("""
import os, glob
from pathlib import Path

def find_dir(pred):
    for root, dirs, files in os.walk("/kaggle/input"):
        if pred(Path(root), dirs, files):
            return Path(root)
    raise FileNotFoundError("dataset layout not found under /kaggle/input")

train_dir = find_dir(lambda r, d, f: "real" in d and "fake" in d)
test_dir  = find_dir(lambda r, d, f: r.name == "images" and len(f) > 100)
folds_csv = next(Path("/kaggle/input").rglob("folds.csv"))

data = Path("/kaggle/working/data"); data.mkdir(exist_ok=True)
if not (data / "train").exists():
    (data / "train").symlink_to(train_dir)
print("train:", train_dir, "| test:", test_dir, "| folds:", folds_csv)
print({k: len(os.listdir(train_dir / k)) for k in ("real", "fake")}, "test:", len(os.listdir(test_dir)))
"""),
    md("## Train"),
    code("""
%cd /kaggle/working/code
for run, extra in RUNS.items():
    for fold in FOLDS:
        print(f"\\n######## {run} | fold {fold} ########", flush=True)
        !python train.py --data_dir /kaggle/working/data --folds_csv {folds_csv} --fold {fold} --workers 4 --run_name {run} --out_dir /kaggle/working/outputs {COMMON} {extra}
"""),
    code("""
import json, os, pandas as pd
rows = []
for run in RUNS:
    for fold in FOLDS:
        d = f"/kaggle/working/outputs/{run}/fold{fold}"
        if not os.path.exists(f"{d}/robustness.json"):
            print(f"!! {run} fold {fold}: no results (run failed?)"); continue
        print(f"== {run} | fold {fold}"); print(pd.read_csv(f"{d}/history.csv").round(4).to_string(index=False))
        r = json.load(open(f"{d}/robustness.json"))
        rows.append({"run": run, "fold": fold, "clean": r["clean"], "mean_degraded": r["mean_degraded"],
                     "worst_degraded": r["worst_degraded"]})
summary = pd.DataFrame(rows)
summary.to_csv("/kaggle/working/summary.csv", index=False)
print("\\n=== SUMMARY (reference fold-0 clean AUC: ml5_drop 0.9166) ===")
print(summary.groupby("run")[["clean", "mean_degraded", "worst_degraded"]].mean().round(4).sort_values("clean", ascending=False))
"""),
    md("## Bundle + timed test inference (T4, same script the judges run)"),
    code("""
import time
if RUN_TEST_INFERENCE and len(summary):
    best_run = summary.groupby("run")["clean"].mean().idxmax()
    print("bundling best run:", best_run)
    out = f"/kaggle/working/outputs/{best_run}"
    !python build_bundle.py --members "{out}/fold*/member.pt" --oof "{out}/fold*/oof.csv" --out /kaggle/working/model_weights.pt
    t0 = time.time()
    !python inference_script.py --test_dir {test_dir} --weights /kaggle/working/model_weights.pt --output /kaggle/working/predictions.csv
    print(f"inference wall time: {time.time() - t0:.1f}s (target < 300s)")
    !head -5 /kaggle/working/predictions.csv; wc -l /kaggle/working/predictions.csv
"""),
]

for i, c in enumerate(cells):
    c["id"] = f"cell-{i:02d}"  # nbformat >= 4.5 requires cell ids

nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                                  "name": "python3"},
                                   "language_info": {"name": "python"}},
      "nbformat": 4, "nbformat_minor": 5}
OUT_DIR.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps(nb, indent=1))
meta = {"id": f"{cli_args.owner}/{SLUG}", "title": SLUG.replace("-", " ").title(),
        "code_file": OUT.name, "language": "python", "kernel_type": "notebook", "is_private": True,
        "enable_gpu": True, "enable_tpu": False, "enable_internet": True, "keywords": [],
        "dataset_sources": [f"{cli_args.owner}/deepfake-hackathon-data"], "kernel_sources": [],
        "competition_sources": [], "model_sources": [], "machine_shape": "NvidiaTeslaT4"}
(OUT_DIR / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
print(f"wrote {OUT} ({len(cells)} cells, folds={FOLDS}, runs={list(RUNS)})")
